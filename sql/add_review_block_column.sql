-- =============================================
-- SPOT_REVIEW 테이블에 review_block 컬럼 추가
-- =============================================
-- 용도: 관리자가 부적절한 리뷰를 차단하기 위한 플래그 컬럼
-- 값 설명:
--   0 = 정상 (기본값) → 화면에 노출됨
--   1 = 차단됨        → 화면에 노출되지 않음
--
-- ※ 이 SQL은 기존 테이블에 컬럼을 추가하는 ALTER문입니다.
--   프로젝트 최초 실행 전에 반드시 실행해주세요.
-- =============================================

ALTER TABLE SPOT_REVIEW
    ADD COLUMN review_block INT NOT NULL DEFAULT 0
    COMMENT '리뷰 차단 여부 (0=정상, 1=차단)'
    AFTER content;
